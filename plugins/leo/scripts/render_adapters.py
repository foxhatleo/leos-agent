def render(config):
    _validate(config)
    outputs = {}
    claude_substituted = _substituted_roles(config, "claude")
    cursor_substituted = _substituted_roles(config, "cursor")
    for role, tier, access in _roles(config):
        # Claude Code agents MUST live at the conventional agents/ path: a
        # manifest "agents" array of file paths validates but silently loads
        # zero agents, and the conventional directory auto-loads.
        if role not in claude_substituted:
            outputs[ROOT / "agents" / f"{role}.md"] = _claude_agent(role, tier, config)
        if role not in cursor_substituted:
            outputs[ROOT / "adapters" / "cursor" / "agents" / f"{role}.md"] = _cursor_agent(
                role, access, config
            )
    outputs[REFERENCE_DIR / "harnesses.md"] = _harness_reference(config)
    outputs[ROOT / "adapters" / "opencode" / "agents.json"] = _opencode_agents(config)
    outputs[ROOT / "README.md"] = _payload_readme(config)

    # The manifest is not rewritten here: per-install model overrides were
    # retired along with the placeholder they fed. Retiering means editing
    # config/models.json and re-running this script, the flow README documents.
    return outputs


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated adapters drift")
    args = parser.parse_args()
    config = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
    outputs = render(config)
    drift = []
    for path, expected in outputs.items():
        if path.exists() and path.read_text(encoding="utf-8") == expected:
            continue
        if args.check:
            drift.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")

    # Stale generated files are drift too. Comparing only what render() would
    # produce is blind to a file that exists and *shouldn't* — a role dropped
    # from models.json, a role newly substituted by a native, a renamed harness
    # — so the orphan survives every --check and ships. Sweep the generated
    # trees and flag anything unclaimed.
    for pattern in (
        "agents/*.md",
        "adapters/cursor/agents/*.md",
        "adapters/opencode/agents.json",
        "README.md",
        "skills/routing/references/*.md",
    ):
        for path in sorted(ROOT.glob(pattern)):
            if path in outputs:
                continue
            rel = path.relative_to(ROOT).as_posix()
            if args.check:
                drift.append(f"{rel} (stale: nothing in config/models.json generates it)")
            else:
                path.unlink()
                print(f"removed stale generated file: {rel}", file=sys.stderr)
    if drift:
        print("generated adapter drift: " + ", ".join(drift), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
