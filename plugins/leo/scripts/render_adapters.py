        "the [repository](https://github.com/foxhatleo/leos-agent) for Claude Code, Codex, "
        "Cursor, and Hermes instructions.\n\n"
        "Supported hosts are macOS, Linux, and WSL with Python 3.9+; native Windows is "
        "unsupported.\n\n"
        "## Install and update\n\n"
        "```sh\nopencode plugin leos-agent --global\n```\n\n"
        "On builds without that subcommand, add `leos-agent` to the `plugin` array in "
